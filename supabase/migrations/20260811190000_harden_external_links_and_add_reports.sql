create table public.content_reports (
  id bigint generated by default as identity primary key,
  reporter_id uuid references public.profiles(id) on delete set null,
  startup_id bigint references public.startups(id) on delete set null,
  link_kind text not null,
  reported_url text not null,
  reason text not null,
  status text not null default 'pending',
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  constraint content_reports_link_kind_check
    check (link_kind in ('website', 'deck')),
  constraint content_reports_url_check
    check (public.is_public_https_url(reported_url)),
  constraint content_reports_reason_check
    check (reason in ('phishing', 'malware', 'misleading', 'privacy', 'other')),
  constraint content_reports_status_check
    check (status in ('pending', 'resolved', 'dismissed')),
  constraint content_reports_review_check
    check (
      (status = 'pending' and reviewed_at is null)
      or (status in ('resolved', 'dismissed') and reviewed_at is not null)
    )
);

create unique index content_reports_one_pending_report_idx
  on public.content_reports (reporter_id, startup_id, link_kind)
  where status = 'pending' and reporter_id is not null;

create index content_reports_pending_created_idx
  on public.content_reports (created_at)
  where status = 'pending';

