-- Treat stored external URLs as public-content boundaries. Application
-- validation provides field errors; these constraints remain authoritative for
-- direct Data API writes.

create or replace function public.external_url_hostname(value text)
returns text
language plpgsql
immutable
strict
security invoker
set search_path = ''
as $$
declare
  authority text;
begin
  if value !~ '^https://' then return null; end if;

  authority := substring(value from '^https://([^/?#]+)');
  if authority is null
    or authority like '%@%'
    or authority like '[%' then
    return null;
  end if;

  if authority ~ ':[0-9]+$' then
    if authority !~ ':443$' then return null; end if;
    authority := regexp_replace(authority, ':443$', '');
  end if;

  return lower(authority);
end;
$$;

create or replace function public.is_public_https_url(value text)
returns boolean
language plpgsql
immutable
strict
security invoker
set search_path = ''
as $$
declare
  hostname text := public.external_url_hostname(value);
begin
  return
    value = btrim(value)
    and char_length(value) <= 2048
    and value !~ '[[:space:]]'
    and hostname is not null
    and hostname ~ '^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?(\.[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?)+$'
    and hostname !~ '^[0-9.]+$'
    and hostname <> 'localhost'
    and hostname !~ '(\.localhost|\.local|\.internal|\.home\.arpa)$';
end;
$$;

create or replace function public.is_pitch_deck_url(value text)
returns boolean
language sql
immutable
strict
security invoker
set search_path = ''
as $$
  select
    public.is_public_https_url(value)
    and (
      value ~* '\.pdf([?#]|$)'
      or public.external_url_hostname(value) in (
        'docsend.com',
        'docs.google.com',
        'drive.google.com',
        'pitch.com',
        'www.docsend.com',
        'www.pitch.com'
      )
    );
$$;

revoke all on function public.external_url_hostname(text) from public;
revoke all on function public.is_public_https_url(text) from public;
revoke all on function public.is_pitch_deck_url(text) from public;

alter table public.startups
  drop constraint if exists startups_website_url_http_check,
  drop constraint if exists startups_deck_url_http_check,
  add constraint startups_website_url_http_check
    check (website_url is null or public.is_public_https_url(website_url)) not valid,
  add constraint startups_deck_url_http_check
    check (deck_url is null or public.is_pitch_deck_url(deck_url)) not valid;

alter table public.profiles
  drop constraint if exists profiles_avatar_url_http_check,
  drop constraint if exists profiles_linkedin_url_check,
  drop constraint if exists profiles_website_url_http_check,
  add constraint profiles_avatar_url_http_check
    check (avatar_url is null or public.is_public_https_url(avatar_url)) not valid,
  add constraint profiles_linkedin_url_check
    check (
      linkedin_url is null
      or (
        public.is_public_https_url(linkedin_url)
        and (
          public.external_url_hostname(linkedin_url) = 'linkedin.com'
          or public.external_url_hostname(linkedin_url) like '%.linkedin.com'
        )
      )
    ) not valid,
  add constraint profiles_website_url_http_check
    check (website_url is null or public.is_public_https_url(website_url)) not valid;

alter table public.profile_contacts
  drop constraint if exists profile_contacts_url_check,
  add constraint profile_contacts_url_check
    check (contact_url is null or public.is_public_https_url(contact_url)) not valid;

