create or replace function public.report_startup_link(
  reported_startup_id bigint,
  reported_link_kind text,
  reported_reason text
)
returns boolean
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  account_id uuid := auth.uid();
  current_url text;
begin
  if account_id is null then
    raise exception using errcode = '42501', message = 'Authentication required';
  end if;

  if reported_link_kind not in ('website', 'deck')
    or reported_reason not in ('phishing', 'malware', 'misleading', 'privacy', 'other') then
    raise exception using errcode = '22023', message = 'Invalid content report';
  end if;

  perform pg_advisory_xact_lock(hashtextextended(account_id::text, 0));

  if (
    select count(*)
    from public.content_reports
    where reporter_id = account_id
      and created_at >= clock_timestamp() - interval '1 hour'
  ) >= 5 then
    raise exception using errcode = 'P0001', message = 'Content report rate limit exceeded';
  end if;

  select case reported_link_kind
    when 'website' then startups.website_url
    when 'deck' then startups.deck_url
  end
  into current_url
  from public.startups
  where startups.id = reported_startup_id
    and startups.is_active;

  if current_url is null then
    raise exception using errcode = '22023', message = 'Reported link is unavailable';
  end if;

  begin
    insert into public.content_reports (
      reporter_id,
      startup_id,
      link_kind,
      reported_url,
      reason
    ) values (
      account_id,
      reported_startup_id,
      reported_link_kind,
      current_url,
      reported_reason
    );
  exception when unique_violation then
    return false;
  end;

  return true;
end;
$$;

revoke all on function public.report_startup_link(bigint, text, text) from public, anon;
grant execute on function public.report_startup_link(bigint, text, text) to authenticated;

comment on table public.content_reports is
  'Operator-only moderation queue for user-reported public startup links.';
comment on function public.report_startup_link(bigint, text, text) is
  'Captures the current persisted link with duplicate and per-account rate limits.';
